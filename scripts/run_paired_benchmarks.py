#!/usr/bin/env python3
"""Run paired benchmarks (--tw 1/0 and --rw 1/0) and compare runtimes.

Expects benchmarks generated by gen_paired_benchmarks.py to live in
tests/benchmarks/ (default).

For each instance, runs ganak twice — once with the structured-dispatch
flag enabled and once disabled (forcing DPLL on the same CNF) — captures
wall time and the result. Reports a comparison table and flags any
answers that differ beyond a small tolerance.
"""

from __future__ import annotations

import argparse
import math
import os
import re
import subprocess
import time
from dataclasses import dataclass


GANAK = "/home/gperez/GIT-repos/ganak/build/ganak"
BENCH_DIR = "/home/gperez/GIT-repos/ganak/tests/benchmarks"

TOL_REL = 1e-6
TOL_ABS = 1e-9


@dataclass
class RunResult:
    wall: float
    answer: complex | float | None
    fell_back: bool
    raw_lines: str


_RE_FLOAT = re.compile(
    r"^c [os] exact quadruple float\s+"
    r"(?P<re>[-+]?\d+\.\d+e[-+]?\d+)"
    r"(?:\s*\+\s*(?P<im>[-+]?\d+\.\d+e[-+]?\d+)i)?",
    re.MULTILINE,
)
_RE_INT = re.compile(r"^c s exact arb int\s+(?P<v>-?\d+)$", re.MULTILINE)
_RE_FRAC = re.compile(r"^c s exact arb frac\s+(?P<n>-?\d+)/(?P<d>\d+)$", re.MULTILINE)


def parse_answer(out: str) -> complex | float | None:
    m = _RE_FLOAT.search(out)
    if m:
        re_v = float(m.group("re"))
        im_v = float(m.group("im")) if m.group("im") else 0.0
        return complex(re_v, im_v)
    m = _RE_INT.search(out)
    if m:
        return float(int(m.group("v")))
    m = _RE_FRAC.search(out)
    if m:
        return float(int(m.group("n"))) / float(int(m.group("d")))
    return None


def run_ganak(cnf: str, flags: list[str], timeout: float) -> RunResult:
    cmd = [GANAK] + flags + [cnf]
    t0 = time.perf_counter()
    try:
        p = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
        out = p.stdout
        wall = time.perf_counter() - t0
    except subprocess.TimeoutExpired:
        return RunResult(wall=timeout, answer=None, fell_back=False, raw_lines="<timeout>")
    fell = "falling back to DPLL" in out
    ans = parse_answer(out)
    return RunResult(wall=wall, answer=ans, fell_back=fell, raw_lines=out)


def answers_agree(a, b) -> bool:
    if a is None or b is None:
        return False
    ca = complex(a)
    cb = complex(b)
    if abs(ca - cb) <= TOL_ABS:
        return True
    denom = max(abs(ca), abs(cb), 1.0)
    return abs(ca - cb) / denom <= TOL_REL


def fmt_ans(a) -> str:
    if a is None:
        return "—"
    c = complex(a)
    if abs(c.imag) < 1e-12:
        return f"{c.real:.6e}"
    return f"{c.real:.6e}{c.imag:+.6e}i"


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--bench", default=BENCH_DIR)
    p.add_argument("--timeout", type=float, default=60.0)
    p.add_argument("--twmaxk", type=int, default=30)
    p.add_argument("--rwmaxk", type=int, default=20)
    args = p.parse_args()

    bench_files = sorted(f for f in os.listdir(args.bench) if f.endswith(".cnf"))

    rw_files = [f for f in bench_files if f.startswith("rw_")]
    tw_files = [f for f in bench_files if f.startswith("tw_")]

    print("=" * 100)
    print(f"{'instance':<22} {'mode':>4} {'n':>4} {'m':>4} {'tw/rw':>6} "
          f"{'structured(s)':>14} {'DPLL(s)':>11} {'speedup':>8}  {'agree':>5}")
    print("=" * 100)

    def parse_header(path: str) -> tuple[int, int]:
        n = m = 0
        with open(path) as fp:
            for line in fp:
                if line.startswith("p cnf"):
                    parts = line.split()
                    n = int(parts[2]); m = int(parts[3])
                    return n, m
        return n, m

    def parse_width(out: str, kind: str) -> str:
        for line in out.splitlines():
            if kind == "tw" and "[tw] incidence-graph treewidth:" in line:
                return line.split("treewidth:")[1].split()[0]
            if kind == "rw" and "[rw] SOP variables:" in line:
                # "... rank-width: K, r: 8"
                for part in line.split(","):
                    if "rank-width" in part:
                        return part.split(":")[1].strip()
        return "?"

    def report(label: str, mode: int, n: int, m: int, width: str,
               on: RunResult, off: RunResult):
        agree = answers_agree(on.answer, off.answer)
        speedup = (off.wall / on.wall) if on.wall > 0 else float("inf")
        note = ""
        if on.fell_back:
            note = " (fell back!)"
        print(f"{label:<22} {mode:>4} {n:>4} {m:>4} {width:>6} "
              f"{on.wall:>14.3f} {off.wall:>11.3f} {speedup:>8.2f}x "
              f"{'OK' if agree else 'MISMATCH'}{note}")
        if not agree:
            print(f"   structured={fmt_ans(on.answer)}")
            print(f"   dpll      ={fmt_ans(off.answer)}")

    # ---- Treewidth benchmarks --------------------------------------------
    print()
    print("Treewidth (--tw 1 vs --tw 0, mode 1, same CNF)")
    print("-" * 100)
    for fname in tw_files:
        path = os.path.join(args.bench, fname)
        n, m = parse_header(path)
        mode = 1
        on  = run_ganak(path, ["--mode", str(mode), "--tw", "1", "--twmaxk", str(args.twmaxk)],
                        timeout=args.timeout)
        off = run_ganak(path, ["--mode", str(mode), "--tw", "0"],
                        timeout=args.timeout)
        width = parse_width(on.raw_lines, "tw")
        report(fname[:-4], mode, n, m, width, on, off)

    # ---- Rank-width benchmarks -------------------------------------------
    print()
    print("Rank-width (--rw 1 vs --rw 0, mode 6, paired CNF w/ aux y-vars)")
    print("-" * 100)
    for fname in rw_files:
        path = os.path.join(args.bench, fname)
        n, m = parse_header(path)
        mode = 6
        on  = run_ganak(path, ["--mode", str(mode), "--rw", "1", "--rwmaxk", str(args.rwmaxk)],
                        timeout=args.timeout)
        off = run_ganak(path, ["--mode", str(mode), "--rw", "0"],
                        timeout=args.timeout)
        width = parse_width(on.raw_lines, "rw")
        report(fname[:-4], mode, n, m, width, on, off)


if __name__ == "__main__":
    main()
